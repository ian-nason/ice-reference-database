args <- commandArgs(TRUE)
if(length(args)>=3 && nzchar(args[[3]])) .libPaths(c(args[[3]],.libPaths()))
library(datapond)
library(DBI)
options(datapond.registry_url=args[[1]],datapond.cache_dir=args[[2]])
stopifnot(identical(dp_list(),"ice-reference"))
con<-dp_connect("ice-reference",quiet=TRUE)
tryCatch({
  dbExecute(con,"SET memory_limit='128MiB'")
  dbExecute(con,'SET threads=1')
  dbExecute(con,"SET max_temp_directory_size='0B'")
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM facilities')$n==878)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM offices')$n==275)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM aor')$n==26)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM county_aor')$n==3231)
  stopifnot(dbGetQuery(con,"SELECT count(*) FROM facilities WHERE detention_facility_code IS NULL")[[1]][[1]]==1)
  stopifnot(dbGetQuery(con,"SELECT count(*) FROM aor WHERE ST_AsText(ST_GeomFromWKB(geometry_wkb)) LIKE '%EMPTY'")[[1]][[1]]==1)
  stopifnot(dbGetQuery(con,"SELECT count(*) FROM county_aor WHERE ST_AsText(ST_GeomFromWKB(geometry_wkb)) LIKE '%EMPTY'")[[1]][[1]]==1)
  stopifnot(dbGetQuery(con,"SELECT count(*) FROM offices WHERE latitude IS NULL AND longitude IS NULL")[[1]][[1]]==5)
  stopifnot(nrow(dp_describe(con))==4)
  example<-dbGetQuery(con,"SELECT state, count(*) AS facilities FROM facilities GROUP BY state ORDER BY facilities DESC, state LIMIT 5")
  cat(jsonlite::toJSON(list(passed=TRUE,client='R datapond',version=as.character(packageVersion('datapond')),duckdb=as.character(packageVersion('duckdb')),example=example),auto_unbox=TRUE))
},finally=dp_disconnect(con))
